import { describe, expect, it } from "vitest";
import { MASK, redact, redactDeep } from "@/lib/privacy/redact";

// 가리기(lib/privacy/redact.ts). 모든 값은 지어낸 가상 값이다.

const masked = (text: string) => redact(text).text;

describe("가릴 것", () => {
  it.each([
    ["주민등록번호", "주민번호 800505-1234567 입니다", "800505"],
    ["뒷자리 일부를 가린 주민번호", "800505-1******", "800505"],
    ["붙여 쓴 주민번호", "8005051234567", "8005051"],
    ["외국인등록번호", "900101-5123456", "900101"],
    ["휴대전화", "연락처 010-1234-5678", "1234-5678"],
    ["띄어 쓴 휴대전화", "010 1234 5678", "5678"],
    ["지역번호 전화", "02-345-6789로", "345-6789"],
    ["이메일", "메일 kim.test@example.co.kr 로", "example"],
    ["차량번호", "차량번호 12가3456", "3456"],
    ["지역이 붙은 차량번호", "서울12가3456", "3456"],
    ["세 자리 차량번호", "123가4567 차량", "4567"],
    ["증권번호 항목", "증권번호: AB1234567", "AB1234567"],
    ["한글이 섞인 증권번호", "증권번호 가상-2026-000123", "000123"],
    ["증권번호 꼴", "번호 2026-1234-567890 확인", "567890"],
    ["숫자만 긴 증권번호", "202612345678 입니다", "202612345678"],
    ["계좌번호", "입금 110-123-456789", "456789"],
    ["계좌 항목", "계좌번호 3333 01 2345678", "2345678"],
    ["카드번호", "카드 4111 1111 1111 1111", "1111 1111"],
    ["계약자 이름", "계약자 홍길동", "홍길동"],
    ["기명피보험자 이름", "기명피보험자: 김가상", "김가상"],
    ["예금주", "예금주 이가상", "이가상"],
    ["주소", "주소: 서울시 가상구 가상로 12, 101동", "가상로"],
  ])("%s", (_, text, secret) => {
    const result = redact(text);
    expect(result.text).not.toContain(secret);
    expect(result.text).toContain(MASK);
    expect(result.count).toBeGreaterThan(0);
  });

  it("말 속의 사람 이름(상대방 실명)을 가린다", () => {
    expect(masked("상대 운전자 김가상 씨가 먼저 내렸어요")).toBe("상대 운전자 ****** 씨가 먼저 내렸어요");
    expect(masked("김가상씨한테 연락했어요")).toBe("******씨한테 연락했어요");
    expect(masked("상대방 이름은 박가상이고")).toBe("상대방 이름은 ******이고");
    expect(masked("홍길동이라는 사람이 박았어요")).toBe("******이라는 사람이 박았어요");
    // 이름이 아닌 말은 남긴다.
    for (const text of ["아저씨가 마음씨 좋게 비켜 줬어요", "날씨가 흐렸고 정말 씨게 박았어요", "이 사람이 박았어요", "상대가 중앙선 침범"]) expect(masked(text)).toBe(text);
  });

  it("한 글에 여러 개가 있으면 모두 가리고 건수를 센다", () => {
    const result = redact("계약자 홍길동 / 주민 800505-1234567 / 010-1234-5678 / 12가3456 / kim@example.com");
    expect(result.count).toBe(5);
    for (const secret of ["홍길동", "800505", "1234-5678", "12가3456", "example"]) expect(result.text).not.toContain(secret);
  });

  it("객체 안의 모든 문자열을 가리고 칸 이름은 그대로 둔다", () => {
    const { value, count } = redactDeep({ note: "010-1234-5678", list: ["12가3456", "자기신체사고"], amount: 3 });
    expect(value).toEqual({ note: MASK, list: [MASK, "자기신체사고"], amount: 3 });
    expect(count).toBe(2);
  });
});

describe("가리면 안 되는 것", () => {
  it.each([
    ["쉼표 금액", "대인배상Ⅱ 무한, 대물배상 30,000,000원"],
    ["한글 금액", "자기신체사고 부상 3천만원 / 사망 1억원"],
    ["억 단위", "1억5천만원"],
    ["날짜", "보험기간 2026-01-01 ~ 2027-01-01"],
    ["점 날짜", "2026.09.01 00:00"],
    ["상해급수와 과실", "상해 7급, 과실 30%, 입원 14일"],
    ["보험사 대표번호", "고객센터 1588-5656 / 1577-1001 / 1566-8000"],
    ["담보 이름", "피보험자 자기신체사고 담보, 기명피보험자 1인 한정"],
    ["운전자 범위", "운전자 범위: 부부한정, 연령 만 30세 이상"],
    ["자기부담금", "자기부담금 20%(최저 20만원, 최고 50만원)"],
    ["쉼표 없는 금액", "치료비 1200000원"],
    ["차명", "차명 쏘나타 2.0 2022년식"],
  ])("%s", (_, text) => {
    expect(masked(text)).toBe(text);
    expect(redact(text).count).toBe(0);
  });
});
